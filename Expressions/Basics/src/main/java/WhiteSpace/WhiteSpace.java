package WhiteSpace;

public class WhiteSpace {

    public static void main(String[] args) {

        //expression - myVariable = 50
        //statement - entire line (int myVariable = 50;)
        //statement - data type end with ;
        int myVariable = 50;

        // entire- statement
        // myVariable++ and myVariable-- are expressions
        myVariable++;
        myVariable--;

        // semicolon is special (indicate terminate)
        // don't need to in one line

        System.out.println("This is a test");

        System.out.println("This is " +
                "another " +
                "test");


    }
}
